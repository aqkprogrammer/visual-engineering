/**
 * Validates all curriculum content and generates `content/.generated/registry.ts`.
 *
 *   pnpm content          validate + generate (runs automatically before dev/build/test/typecheck)
 *
 * Exits non-zero on any content issue so CI fails with every problem listed at once.
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { CONTENT_DIR, loadCatalog } from "../lib/content/load";

const OUT_DIR = path.join(CONTENT_DIR, ".generated");

async function main() {
  const { domains, lessons, playground, issues } = await loadCatalog();

  if (issues.length > 0) {
    console.error(`\n✖ ${issues.length} content issue(s):\n`);
    for (const issue of issues) console.error(`  • ${issue.where}: ${issue.message}`);
    console.error("");
    process.exit(1);
  }

  const lessonData = lessons.map(
    ({ plainText: _plainText, sourcePath: _sourcePath, ...lesson }) => lesson,
  );
  const loaders = lessons
    .map((l) => `  ${JSON.stringify(l.id)}: () => import("../${l.sourcePath}/index.mdx"),`)
    .join("\n");

  const registry = `// AUTO-GENERATED by scripts/content.ts — do not edit. Run \`pnpm content\` to regenerate.
import type { MDXContent } from "mdx/types";
import type { Domain, Lesson, PlaygroundDemo } from "@/lib/content/schema";

export const domains: Domain[] = ${JSON.stringify(domains, null, 2)};

export const lessons: Lesson[] = ${JSON.stringify(lessonData, null, 2)};

export const playground: PlaygroundDemo[] = ${JSON.stringify(playground, null, 2)};

export const lessonBodies: Record<string, () => Promise<{ default: MDXContent }>> = {
${loaders}
};
`;

  await mkdir(OUT_DIR, { recursive: true });
  await writeFile(path.join(OUT_DIR, "registry.ts"), registry);

  const published = lessons.filter((l) => l.status === "published").length;
  console.log(
    `✓ content valid — ${domains.length} domains, ${lessons.length} lessons (${published} published), ${playground.length} playground demos`,
  );
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
